#!/usr/bin/env python3
"""Subset Kodamaya's fonts to the characters the game actually uses.

Scans src/ for every character in the source, then writes tiny woff2 files to
src/assets/fonts/gen/ plus fonts.css (@font-face rules with unicode-range), so
the single-file build only carries the glyphs we need.

  python3 tools/fonts/build_fonts.py
"""
import io, os, re, sys, glob, json
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(SRC, 'assets', 'fonts', 'gen')
NM = os.path.join(ROOT, 'node_modules')

# ---------------------------------------------------------------- characters
chars = set(chr(c) for c in range(0x20, 0x7f))
chars |= set('¥・「」『』〜！？、。ー…—–‘’“”×÷°♪★☆♥←→↑↓')
kana = set(chr(c) for c in range(0x3041, 0x3097)) | set(chr(c) for c in range(0x30a1, 0x30fb)) | {'ー'}
for path in glob.glob(os.path.join(SRC, '**', '*.*'), recursive=True):
    if not path.endswith(('.js', '.css', '.html', '.json')) or '/assets/fonts/' in path:
        continue
    with open(path, encoding='utf-8', errors='ignore') as f:
        txt = f.read()
    for ch in txt:
        if ord(ch) >= 0x80:
            chars.add(ch)
chars.discard('﻿')
print(f'{len(chars)} characters used ({sum(1 for c in chars if ord(c) > 0x3000)} CJK/kana)')

os.makedirs(OUT, exist_ok=True)
for f in glob.glob(os.path.join(OUT, '*')):
    os.remove(f)

def subset_font(src_path, text, out_path):
    font = TTFont(src_path)
    cmap = font.getBestCmap()
    keep = [c for c in text if ord(c) in cmap]
    if not keep:
        return 0
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    opts.hinting = False
    sub = subset.Subsetter(options=opts)
    sub.populate(text=''.join(keep))
    sub.subset(font)
    font.flavor = 'woff2'
    font.save(out_path)
    return len(keep)

css = ['/* generated by tools/fonts/build_fonts.py - do not edit */']
total = 0
# ---- Galmuri pixel fonts (whole font -> one subset)
GAL = [('Galmuri11', 'Galmuri11.ttf', 400), ('Galmuri11', 'Galmuri11-Bold.ttf', 700), ('Galmuri9', 'Galmuri9.ttf', 400), ('Galmuri7', 'Galmuri7.ttf', 400), ('Galmuri14', 'Galmuri14.ttf', 400)]
for fam, fn, wt in GAL:
    src = os.path.join(NM, 'galmuri', 'dist', fn)
    out_name = fn.replace('.ttf', '.sub.woff2')
    n = subset_font(src, ''.join(sorted(chars | kana)), os.path.join(OUT, out_name))
    size = os.path.getsize(os.path.join(OUT, out_name)) if n else 0
    total += size
    css.append(f"@font-face {{ font-family: '{fam}'; font-weight: {wt}; font-style: normal; font-display: block; src: url('./{out_name}') format('woff2'); }}")
    print(f'  {fam} {wt}: {n} glyphs, {size // 1024} KB')

# ---- fontsource display fonts: keep only the unicode-range files we need, subset each
def parse_ranges(rng):
    out = []
    for part in rng.split(','):
        part = part.strip().replace('U+', '')
        if not part:
            continue
        if '-' in part:
            a, b = part.split('-')
            out.append((int(a, 16), int(b, 16)))
        elif '?' in part:
            out.append((int(part.replace('?', '0'), 16), int(part.replace('?', 'f'), 16)))
        else:
            v = int(part, 16)
            out.append((v, v))
    return out

# (DotGothic16, Rampart One, Potta One and Reggae One were dropped: unused, and they kept the single-file build heavy)
DISPLAY = ['dela-gothic-one', 'rocknroll-one', 'mochiy-pop-one', 'yusei-magic', 'hachi-maru-pop']
from fontTools.merge import Merger, Options as MergeOptions
for pkg in DISPLAY:
    d = os.path.join(NM, '@fontsource', pkg)
    if not os.path.isdir(d):
        continue
    with open(os.path.join(d, 'index.css'), encoding='utf-8') as f:
        txt = f.read()
    fam = re.search(r"font-family: '([^']+)'", txt).group(1)
    parts = []
    for m in re.finditer(r"src: url\(\./files/([^)]+?\.woff2)\)[^;]*;\s*unicode-range: ([^;]+);", txt):
        fn, rng = m.group(1), m.group(2)
        ranges = parse_ranges(rng)
        need = ''.join(c for c in sorted(chars) if any(a <= ord(c) <= b for a, b in ranges))
        if not need:
            continue
        tmp_woff = os.path.join(OUT, f'_{pkg}-{len(parts)}.woff2')
        if not subset_font(os.path.join(d, 'files', fn), need, tmp_woff):
            continue
        t = TTFont(tmp_woff)
        t.flavor = None
        tmp_ttf = tmp_woff.replace('.woff2', '.ttf')
        t.save(tmp_ttf)
        os.remove(tmp_woff)
        parts.append(tmp_ttf)
    if not parts:
        continue
    out_name = f'{pkg}.woff2'
    merged = Merger(options=MergeOptions(drop_tables=['vhea', 'vmtx'])).merge(parts) if len(parts) > 1 else TTFont(parts[0])
    merged.flavor = 'woff2'
    merged.save(os.path.join(OUT, out_name))
    for pth in parts:
        os.remove(pth)
    sz = os.path.getsize(os.path.join(OUT, out_name))
    total += sz
    css.append(f"@font-face {{ font-family: '{fam}'; font-weight: 400; font-style: normal; font-display: block; src: url('./{out_name}') format('woff2'); }}")
    print(f'  {fam}: {len(parts)} parts merged, {sz // 1024} KB')

with open(os.path.join(OUT, 'fonts.css'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(css) + '\n')
with open(os.path.join(OUT, 'families.json'), 'w', encoding='utf-8') as f:
    json.dump(sorted(set(re.findall(r"font-family: '([^']+)'", '\n'.join(css)))), f)
print(f'total {total // 1024} KB -> {os.path.relpath(OUT, ROOT)}')
